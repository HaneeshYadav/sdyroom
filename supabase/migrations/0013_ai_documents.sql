-- Policy helper: does the CALLER own this resource?
-- `study_resources.owner_id` deliberately carries no SELECT grant for the API
-- roles (0005 withholds it; `resource_owner_ids` exists for the same reason),
-- and a policy expression on ANOTHER table enforces column privileges like any
-- query — so the ownership test has to run as the definer, the same pattern
-- 0010 uses for `resource_quota`. Returns a boolean for one id and reveals
-- nothing the caller could not learn from `resource_owner_ids`.
create or replace function public.is_resource_owner(p_resource_id uuid)
returns boolean
language sql
security definer
set search_path = ''
stable
as $$
  select exists (
    select 1
      from public.study_resources s
     where s.id = p_resource_id
       and s.owner_id = auth.uid()
  );
$$;

revoke execute on function public.is_resource_owner(uuid) from public, anon;
grant execute on function public.is_resource_owner(uuid) to authenticated;

-- Read: the same audience as `study_resources` — your own documents, plus
-- documents shared into rooms you are a member of right now. An uploader
-- keeps access to their own shared document after leaving the room, exactly
-- as the resource row policy in 0005 does.
create policy "study_ai_documents_select_visible"
  on public.study_ai_documents
  for select to authenticated
  using (
    exists (
      select 1
      from public.study_resources s
      where s.id = study_ai_documents.resource_id
        and (
          public.is_resource_owner(s.id)
          or (
            s.room_id is not null
            and exists (
              select 1
              from public.room_members m
              where m.room_id = s.room_id
                and m.user_id = auth.uid()
            )
          )
        )
    )
  );

-- No INSERT/UPDATE/DELETE policy exists on purpose: with no matching grant
-- the policies can never be reached, and with no grant the privileges are
-- absent even if a policy were added later. Two independent layers.
-- Joins `study_resources` directly through the chunk's resource id — the
-- audience is identical to the document row's, and the direct join keeps the
-- policy from re-entering the `study_ai_documents` policy it sits beside.
create policy "document_chunks_select_visible"
  on public.document_chunks
  for select to authenticated
  using (
    exists (
      select 1
      from public.study_resources s
      where s.id = document_chunks.resource_id
        and (
          public.is_resource_owner(s.id)
          or (
            s.room_id is not null
            and exists (
              select 1
              from public.room_members m
              where m.room_id = s.room_id
                and m.user_id = auth.uid()
            )
          )
        )
    )
  );

create policy "ai_usage_select_own"
  on public.ai_usage
  for select to authenticated
  using (user_id = auth.uid());

-- ---------------------------------------------------------------------------
-- Helper: authorization + gates for one resource (not exposed to API roles)
-- ---------------------------------------------------------------------------
-- Raises P0001 with a documented message the route maps to a status:
--   not_found              no such resource
--   not_resource_owner     personal resource, caller is not the owner
--   not_member             room resource, caller is not a member of its room
--   too_large              size exceeds the ingest ceiling (20 MiB, mirroring
--                          the upload ceiling from 0005)
--   unsupported_media_type content type is not one of the indexable types
-- 42501/unauthenticated when there is no session at all.
create or replace function public.ai_resource_for_ingest(p_resource_id uuid)
returns public.study_resources
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_resource public.study_resources;
  v_max_bytes constant bigint := 20971520; -- 20 MiB, same as the upload cap
begin
  if v_user is null then
    raise exception 'unauthenticated' using errcode = '42501';
  end if;

  if p_resource_id is null then
    raise exception 'not_found' using errcode = 'P0001';
  end if;

  select * into v_resource
    from public.study_resources
   where id = p_resource_id;

  if not found then
    raise exception 'not_found' using errcode = 'P0001';
  end if;

  -- Type and size gates are re-checked here, independently of the route, so
  -- PR 10's upload rules cannot be routed around on the ingest path either.
  if v_resource.content_type not in (
    'application/pdf',
    'text/plain',
    'text/markdown',
    'text/csv',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
  ) then
    raise exception 'unsupported_media_type' using errcode = 'P0001';
  end if;

  if v_resource.size_bytes > v_max_bytes then
    raise exception 'too_large' using errcode = 'P0001';
  end if;

  if v_resource.room_id is null then
    if v_resource.owner_id <> v_user then
      raise exception 'not_resource_owner' using errcode = 'P0001';
    end if;
  elsif not exists (
    select 1
      from public.room_members m
     where m.room_id = v_resource.room_id
       and m.user_id = v_user
  ) then
    raise exception 'not_member' using errcode = 'P0001';
  end if;

  return v_resource;
end;
$$;

revoke execute on function public.ai_resource_for_ingest(uuid)
  from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ingest_begin — authz, gates, upsert, retry-resume
-- ---------------------------------------------------------------------------
-- Called at the top of every ingest request (route and sweep alike). It is
-- the only place a `study_ai_documents` row is created:
--   * a new row starts at `extracting` (the session begins with the extract
--     step that this same request is about to run — `pending` remains a valid
--     stored state for manually created rows but is never left behind here);
--   * an existing `failed` row is explicitly retried: it resumes at
--     `chunking` when extracted text survived, otherwise at `extracting`.
--     That retry only happens because somebody POSTed the ingest route — the
--     sweep never touches `failed` rows;
--   * `ready`, `embedding`, `chunking`, `extracting` are returned unchanged
--     (idempotent).
create or replace function public.ingest_begin(p_resource_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_resource public.study_resources;
  v_doc public.study_ai_documents;
  v_status text;
  v_error text;
begin
  v_resource := public.ai_resource_for_ingest(p_resource_id);

  select * into v_doc
    from public.study_ai_documents
   where resource_id = p_resource_id
     for update;

  if not found then
    insert into public.study_ai_documents (
      resource_id, status, started_at, updated_at
    )
    values (p_resource_id, 'extracting', now(), now())
    returning * into v_doc;
  elsif v_doc.status = 'failed' then
    update public.study_ai_documents
       set status = case
             when extracted_text is not null and btrim(extracted_text) <> ''
               then 'chunking'
             else 'extracting'
           end,
           error_code = null,
           completed_at = null,
           started_at = coalesce(started_at, now()),
           updated_at = now()  -- explicit: this IS a state change, stamp now()
     where resource_id = p_resource_id
    returning * into v_doc;
  elsif v_doc.status = 'pending' then
    update public.study_ai_documents
       set status = 'extracting',
           started_at = coalesce(started_at, now()),
           updated_at = now()
     where resource_id = p_resource_id
    returning * into v_doc;
  end if;

  return jsonb_build_object(
    'status', v_doc.status,
    'error_code', v_doc.error_code,
    'is_owner', v_resource.owner_id = auth.uid(),
    'room_id', v_resource.room_id,
    'title', v_resource.title,
    'content_type', v_resource.content_type,
    'size_bytes', v_resource.size_bytes,
    'chunk_count', v_doc.chunk_count,
    'extracted_bytes', v_doc.extracted_bytes,
    'embedding_tokens', v_doc.embedding_tokens,
    'model', v_doc.model
  );
end;
$$;

revoke execute on function public.ingest_begin(uuid) from public, anon;
grant execute on function public.ingest_begin(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ingest_record_extraction — store normalized text, advance to chunking
-- ---------------------------------------------------------------------------
-- The extract step writes once, after extraction succeeded:
--   * empty text is refused here as well (the route already checks) — a
--     document with no text layer cannot be indexed;
--   * oversized extracted text (> 16 MiB, possible with a small but highly
--     compressible PDF) lands in `failed` with `extracted_too_large` rather
--     than being stored;
--   * a row that is already `embedding`/`ready` answers with a no-op — a
--     late duplicate can never regress a finished document.
create or replace function public.ingest_record_extraction(
  p_resource_id uuid,
  p_text text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_resource public.study_resources;
  v_doc public.study_ai_documents;
  v_bytes bigint;
begin
  v_resource := public.ai_resource_for_ingest(p_resource_id);
  v_bytes := coalesce(octet_length(p_text), 0);

  select * into v_doc
    from public.study_ai_documents
   where resource_id = p_resource_id
     for update;

  if not found then
    raise exception 'ingest_failed' using errcode = 'P0001';
  end if;

  if v_doc.status in ('embedding', 'ready') then
    return jsonb_build_object(
      'status', v_doc.status,
      'error_code', v_doc.error_code,
      'noop', true
    );
  end if;

  if v_doc.status = 'failed' then
    raise exception 'invalid_state' using errcode = 'P0001';
  end if;

  if v_bytes = 0 or btrim(p_text) = '' then
    update public.study_ai_documents
       set status = 'failed',
           error_code = 'no_text_layer',
           extracted_text = null,
           extracted_bytes = 0,
           completed_at = now()
     where resource_id = p_resource_id
    returning * into v_doc;
  elsif v_bytes > 16777216 then -- 16 MiB of extracted text
    update public.study_ai_documents
       set status = 'failed',
           error_code = 'extracted_too_large',
           extracted_text = null,
           extracted_bytes = 0,
           completed_at = now()
     where resource_id = p_resource_id
    returning * into v_doc;
  else
    update public.study_ai_documents
       set status = 'chunking',
           error_code = null,
           extracted_text = p_text,
           extracted_bytes = v_bytes
     where resource_id = p_resource_id
    returning * into v_doc;
  end if;

  return jsonb_build_object(
    'status', v_doc.status,
    'error_code', v_doc.error_code
  );
end;
$$;

revoke execute on function public.ingest_record_extraction(uuid, text)
  from public, anon;
grant execute on function public.ingest_record_extraction(uuid, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ingest_record_chunks — store chunk drafts, advance to embedding
-- ---------------------------------------------------------------------------
-- The chunk step is deterministic and vector-free: it parks the drafts so the
-- embed step (a later request, possibly a later tab session) can attach
-- provider vectors without re-reading the document. Validated defensively
-- because the function is reachable by direct RPC callers as well as by the
-- route.
create or replace function public.ingest_record_chunks(
  p_resource_id uuid,
  p_chunks jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_doc public.study_ai_documents;
  v_count int;
begin
  perform public.ai_resource_for_ingest(p_resource_id);

  if jsonb_typeof(p_chunks) is distinct from 'array' then
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  v_count := jsonb_array_length(p_chunks);
  if v_count < 1 or v_count > 5000 then
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  if octet_length(p_chunks::text) > 20971520 then
    raise exception 'too_large' using errcode = 'P0001';
  end if;

  select * into v_doc
    from public.study_ai_documents
   where resource_id = p_resource_id
     for update;

  if not found then
    raise exception 'ingest_failed' using errcode = 'P0001';
  end if;

  if v_doc.status = 'ready' then
    return jsonb_build_object('status', 'ready', 'noop', true);
  end if;

  if v_doc.status not in ('chunking', 'embedding') then
    raise exception 'invalid_state' using errcode = 'P0001';
  end if;

  update public.study_ai_documents
     set status = 'embedding',
         error_code = null,
         pending_chunks = p_chunks
   where resource_id = p_resource_id
  returning * into v_doc;

  return jsonb_build_object(
    'status', 'embedding',
    'chunks', v_count
  );
end;
$$;

revoke execute on function public.ingest_record_chunks(uuid, jsonb)
  from public, anon;
grant execute on function public.ingest_record_chunks(uuid, jsonb)
  to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ingest_record_chunk — attach vectors, flip to ready, ledger the spend
-- ---------------------------------------------------------------------------
-- The embed step's single atomic write:
--   * authorization re-checked (independent of the route);
--   * the daily byte cap is re-checked HERE (race-safe authority — a direct
--     RPC loop cannot outrun the route's pre-check);
--   * an idempotency guard: a row that is already `ready` answers with a
--     no-op, so a duplicate concurrent embed converges on the same
--     `chunk_count` and never duplicates rows (`unique (resource_id,
--     ordinal)` is the backstop);
--   * existing chunks for a not-ready row are deleted first, so a re-run
--     after a partial failure replaces rather than appends;
--   * `chunk_hash` is computed here from the authoritative inputs — a client
--     payload cannot supply it;
--   * `ai_usage` gains one `embed_bytes` and one `embed_tokens` row, and the
--     transient columns are cleared.
create or replace function public.ingest_record_chunk(
  p_resource_id uuid,
  p_chunks jsonb,
  p_model text,
  p_tokens bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_resource public.study_resources;
  v_doc public.study_ai_documents;
  v_daily_limit constant bigint := 52428800; -- 50 MiB embedded bytes / scope / day
  v_day_start timestamptz := date_trunc('day', now() at time zone 'utc') at time zone 'utc';
  v_used bigint;
  v_add_bytes bigint := 0;
  v_total bigint := 0;
  v_entry jsonb;
  v_ordinal int;
  v_text text;
  v_tokens int;
  v_page int;
  v_heading text;
  v_embedding extensions.vector(1536);
  v_hash text;
begin
  v_resource := public.ai_resource_for_ingest(p_resource_id);

  if jsonb_typeof(p_chunks) is distinct from 'array' then
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  v_total := jsonb_array_length(p_chunks);
  if v_total < 1 or v_total > 5000 then
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  if p_model is null or char_length(p_model) between 1 and 120 then
    null;
  else
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  if p_tokens is null or p_tokens < 0 or p_tokens > 1000000000 then
    raise exception 'invalid_chunk' using errcode = '22023';
  end if;

  -- Per-chunk validation happens before any write; everything runs in one
  -- transaction, so a failure at any point leaves the previous state intact.
  for v_entry in select value from jsonb_array_elements(p_chunks)
  loop
    if jsonb_typeof(v_entry) <> 'object'
       or jsonb_typeof(v_entry -> 'ordinal') <> 'number'
       or jsonb_typeof(v_entry -> 'text') <> 'string'
       or jsonb_typeof(v_entry -> 'tokens') <> 'number'
       or jsonb_typeof(v_entry -> 'embedding') <> 'array' then
      raise exception 'invalid_chunk' using errcode = '22023';
    end if;

    v_ordinal := (v_entry ->> 'ordinal')::int;
    v_text := v_entry ->> 'text';
    v_tokens := (v_entry ->> 'tokens')::int;

    if v_ordinal < 0
       or v_ordinal >= v_total
       or char_length(v_text) < 1
       or char_length(v_text) > 16000
       or v_tokens < 1
       or v_tokens > 100000 then
      raise exception 'invalid_chunk' using errcode = '22023';
    end if;

    if jsonb_array_length(v_entry -> 'embedding') <> 1536 then
      raise exception 'invalid_chunk' using errcode = '22023';
    end if;

    v_page := case
      when jsonb_typeof(v_entry -> 'page_start') = 'number'
        then (v_entry ->> 'page_start')::int
      else null
    end;
    v_heading := case
      when jsonb_typeof(v_entry -> 'heading') = 'string'
        then v_entry ->> 'heading'
      else null
    end;

    if (v_page is not null and (v_page < 1 or v_page > 1000000))
       or (v_heading is not null and char_length(v_heading) > 500) then
      raise exception 'invalid_chunk' using errcode = '22023';
    end if;

    -- Textual cast of the vector: a non-numeric element fails the vector cast
    -- here (22P02) and rolls the whole call back; a wrong width is refused by
    -- the jsonb_array_length check above and by the column definition.
    v_embedding := (
      select ('[' || string_agg(value::text, ',') || ']')::extensions.vector
        from jsonb_array_elements(v_entry -> 'embedding')
    );
    if extensions.vector_dims(v_embedding) <> 1536 then
      raise exception 'invalid_chunk' using errcode = '22023';
    end if;

    v_add_bytes := v_add_bytes + octet_length(v_text);
  end loop;

  select * into v_doc
    from public.study_ai_documents
   where resource_id = p_resource_id
     for update;

  if not found then
    raise exception 'ingest_failed' using errcode = 'P0001';
  end if;

  if v_doc.status = 'ready' then
    return jsonb_build_object(
      'status', 'ready',
      'noop', true,
      'chunk_count', v_doc.chunk_count,
      'tokens', v_doc.embedding_tokens,
      'model', v_doc.model
    );
  end if;

  if v_doc.status <> 'embedding' then
    raise exception 'invalid_state' using errcode = 'P0001';
  end if;

  -- Daily cap, scoped exactly like the ledger write below: personal spend is
  -- counted per user, room spend per room (shared across members).
  if v_resource.room_id is null then
    select coalesce(sum(u.amount), 0)
      into v_used
      from public.ai_usage u
     where u.kind = 'embed_bytes'
       and u.user_id = auth.uid()
       and u.room_id is null
       and u.created_at >= v_day_start;
  else
    select coalesce(sum(u.amount), 0)
      into v_used
      from public.ai_usage u
     where u.kind = 'embed_bytes'
       and u.room_id = v_resource.room_id
       and u.created_at >= v_day_start;
  end if;

  if v_used + v_add_bytes > v_daily_limit then
    raise exception 'ai_quota_exceeded' using errcode = 'P0001';
  end if;

  delete from public.document_chunks
   where resource_id = p_resource_id;

  insert into public.document_chunks (
    resource_id, ordinal, text, tokens, embedding, page_start, heading, chunk_hash
  )
  select
    p_resource_id,
    (entry ->> 'ordinal')::int,
    entry ->> 'text',
    (entry ->> 'tokens')::int,
    (
      select ('[' || string_agg(v2.value::text, ',') || ']')::extensions.vector
        from jsonb_array_elements(entry -> 'embedding') v2
    ),
    case
      when jsonb_typeof(entry -> 'page_start') = 'number'
        then (entry ->> 'page_start')::int
      else null
    end,
    case
      when jsonb_typeof(entry -> 'heading') = 'string'
        then entry ->> 'heading'
      else null
    end,
    encode(
      pg_catalog.sha256(
        convert_to(
          p_resource_id::text || (entry ->> 'ordinal')::text || (entry ->> 'text'),
          'UTF8'
        )
      ),
      'hex'
    )
  from jsonb_array_elements(p_chunks) as entry;

  update public.study_ai_documents
     set status = 'ready',
         error_code = null,
         chunk_count = v_total,
         embedding_tokens = p_tokens,
         model = p_model,
         completed_at = now(),
         extracted_text = null,
         pending_chunks = null
   where resource_id = p_resource_id
  returning * into v_doc;

  insert into public.ai_usage (room_id, user_id, kind, amount)
  values
    (v_resource.room_id, auth.uid(), 'embed_bytes', v_add_bytes),
    (v_resource.room_id, auth.uid(), 'embed_tokens', p_tokens);

  return jsonb_build_object(
    'status', 'ready',
    'chunk_count', v_total,
    'tokens', p_tokens,
    'model', p_model
  );
end;
$$;

revoke execute on function public.ingest_record_chunk(uuid, jsonb, text, bigint)
  from public, anon;
grant execute on function public.ingest_record_chunk(uuid, jsonb, text, bigint)
  to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ingest_mark_failed — record a safe, retryable failure
-- ---------------------------------------------------------------------------
-- `p_status` matters for resumability (spec's positive guarantee): a provider
-- or quota failure during the embed step keeps the row at `embedding` with an
-- `error_code`, never silently `ready` and never a `failed` that would throw
-- away the extracted text. Extraction failures use the default `failed`.
-- A `ready` row is never un-readied — the call becomes a no-op.
create or replace function public.ingest_mark_failed(
  p_resource_id uuid,
  p_error_code text,
  p_status text default 'failed'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_doc public.study_ai_documents;
begin
  perform public.ai_resource_for_ingest(p_resource_id);

  if p_error_code is null
     or p_error_code not in (
       'no_text_layer',
       'extract_failed',
       'extracted_too_large',
       'ingest_failed',
       'ai_quota_exceeded',
       'ai_provider_failed'
     ) then
    raise exception 'invalid_error_code' using errcode = '22023';
  end if;

  if p_status not in ('failed', 'extracting', 'chunking', 'embedding', 'pending') then
    raise exception 'invalid_state' using errcode = '22023';
  end if;

  select * into v_doc
    from public.study_ai_documents
   where resource_id = p_resource_id
     for update;

  if not found then
    raise exception 'ingest_failed' using errcode = 'P0001';
  end if;

  if v_doc.status = 'ready' then
    return jsonb_build_object('status', 'ready', 'noop', true);
  end if;

  update public.study_ai_documents
     set status = p_status,
         error_code = p_error_code,
         completed_at = case when p_status = 'failed' then now() else completed_at end
   where resource_id = p_resource_id
  returning * into v_doc;

  return jsonb_build_object(
    'status', v_doc.status,
    'error_code', v_doc.error_code
  );
end;
$$;

revoke execute on function public.ingest_mark_failed(uuid, text, text)
  from public, anon;
grant execute on function public.ingest_mark_failed(uuid, text, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: match_document_chunks — the single retrieval entry point (PRs 13–16)
-- ---------------------------------------------------------------------------
-- SECURITY DEFINER with the guard inside (spec allows this or an invoker with
-- an explicit guard): the definer role bypasses RLS, so the authorization
-- lives in the WHERE clause, and it is deliberately complete:
--   * room scope: caller must be a member of `p_room_id` (checked against
--     `room_members` directly) AND the resource must live in that room —
--     cross-room rows cannot match;
--   * personal scope (`p_room_id is null`): only the caller's own
--     `room_id is null` resources;
--   * only `status = 'ready'` documents contribute chunks.
-- A non-member with a perfectly crafted embedding gets zero rows: the
-- membership guard fails before similarity is computed.
--
-- Score is cosine similarity in [-1, 1] (`1 - (embedding <=> query)`),
-- returned only above `p_threshold`, ordered best-first with stable
-- tie-breaks so pagination and tests are deterministic.
--
-- Returns the resource title and room id so `lib/ai/retrieve.ts` can assemble
-- citations without a second query; never returns the embedding itself.
create or replace function public.match_document_chunks(
  p_room_id uuid,
  p_query_embedding extensions.vector(1536),
  p_limit int default 8,
  p_threshold float8 default 0.2
)
returns table (
  resource_id uuid,
  chunk_id uuid,
  ordinal int,
  text text,
  title text,
  room_id uuid,
  score float8,
  page_start int,
  heading text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_limit int := coalesce(p_limit, 8);
  v_threshold float8 := coalesce(p_threshold, 0.2);
begin
  if auth.uid() is null then
    return;
  end if;

  if v_limit < 1 then
    v_limit := 1;
  elsif v_limit > 50 then
    v_limit := 50;
  end if;

  if p_room_id is not null and not exists (
    select 1
      from public.room_members m
     where m.room_id = p_room_id
       and m.user_id = auth.uid()
  ) then
    return;
  end if;

  if p_query_embedding is null then
    return;
  end if;

  return query
    select
      c.resource_id,
      c.id,
      c.ordinal,
      c.text,
      s.title,
      s.room_id,
      (1 - (c.embedding operator(extensions.<=>) p_query_embedding))::float8,
      c.page_start,
      c.heading
      from public.document_chunks c
      join public.study_ai_documents d on d.resource_id = c.resource_id
      join public.study_resources s on s.id = d.resource_id
     where d.status = 'ready'
       and (
         (p_room_id is not null and s.room_id = p_room_id)
         or (
           p_room_id is null
           and s.room_id is null
           and s.owner_id = auth.uid()
         )
       )
       and (1 - (c.embedding operator(extensions.<=>) p_query_embedding)) >= v_threshold
     order by
       (1 - (c.embedding operator(extensions.<=>) p_query_embedding)) desc,
       c.resource_id,
       c.ordinal
     limit v_limit;
end;
$$;

revoke execute on function public.match_document_chunks(uuid, extensions.vector, int, float8)
  from public, anon;
grant execute on function public.match_document_chunks(uuid, extensions.vector, int, float8)
  to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: ai_usage_daily — today's embed spend for one scope
-- ---------------------------------------------------------------------------
-- Personal scope (`p_room_id is null`): the caller's own ledger. Room scope:
-- the whole room's ledger for today — the cap is per room per day and shared
-- across members, so the numbers must match what the cap enforces.
-- `p_user_id` must be the caller: it never becomes a way to read someone
-- else's personal ledger.
create or replace function public.ai_usage_daily(
  p_user_id uuid,
  p_room_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_daily_limit constant bigint := 52428800; -- 50 MiB embedded bytes / scope / day
  v_day_start timestamptz := date_trunc('day', now() at time zone 'utc') at time zone 'utc';
  v_bytes bigint := 0;
  v_tokens bigint := 0;
begin
  if auth.uid() is null then
    raise exception 'unauthenticated' using errcode = '42501';
  end if;

  if p_user_id is distinct from auth.uid() then
    raise exception 'not_authorized' using errcode = '42501';
  end if;

  if p_room_id is not null and not exists (
    select 1
      from public.room_members m
     where m.room_id = p_room_id
       and m.user_id = auth.uid()
  ) then
    raise exception 'not_found' using errcode = 'P0001';
  end if;

  if p_room_id is null then
    select
      coalesce(sum(amount) filter (where kind = 'embed_bytes'), 0),
      coalesce(sum(amount) filter (where kind = 'embed_tokens'), 0)
      into v_bytes, v_tokens
      from public.ai_usage
     where user_id = auth.uid()
       and room_id is null
       and created_at >= v_day_start;
  else
    select
      coalesce(sum(amount) filter (where kind = 'embed_bytes'), 0),
      coalesce(sum(amount) filter (where kind = 'embed_tokens'), 0)
      into v_bytes, v_tokens
      from public.ai_usage
     where room_id = p_room_id
       and created_at >= v_day_start;
  end if;

  return jsonb_build_object(
    'scope', case when p_room_id is null then 'user' else 'room' end,
    'used_bytes', v_bytes,
    'used_tokens', v_tokens,
    'limit_bytes', v_daily_limit,
    'day_start', v_day_start
  );
end;
$$;

revoke execute on function public.ai_usage_daily(uuid, uuid) from public, anon;
grant execute on function public.ai_usage_daily(uuid, uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- RPC: resource_owner_ids — which of these ids does the caller own?
-- ---------------------------------------------------------------------------
-- The owner-only "Index now" button needs an ownership signal that
-- `study_resources` deliberately does not expose (`owner_id` has no SELECT
-- grant — see 0005). One batched call gives the list pages and
-- `GET /api/resources` exactly that signal and nothing more: ids the caller
-- does not own come back absent, and a caller with no session gets nothing.
-- SECURITY DEFINER because `owner_id` itself must never be readable.
create or replace function public.resource_owner_ids(p_resource_ids uuid[])
returns setof uuid
language sql
security definer
set search_path = ''
stable
as $$
  select s.id
    from public.study_resources s
   where s.id = any(p_resource_ids)
     and s.owner_id = auth.uid();
$$;

revoke execute on function public.resource_owner_ids(uuid[]) from public, anon;
grant execute on function public.resource_owner_ids(uuid[]) to authenticated;
