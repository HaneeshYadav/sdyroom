-- 0013_ai_documents.sql
-- AI document foundation: ingestion state, chunks, embeddings, usage ledger.
--
-- Migration numbering: PR 12's specification pre-assignment said `0012`, but
-- 0012 was taken by `0012_notifications.sql` when PR 11 merged to main. The
-- next free version is 0013, so this is `0013_ai_documents.sql` — unique
-- against origin/main and this branch. 0014+ remain reserved for the later AI
-- PRs (see docs/PR_ROADMAP.md §3 "Migration-number rule").
--
-- ---------------------------------------------------------------------------
-- EMBEDDING DIMENSION — READ BEFORE CHANGING ANYTHING
-- ---------------------------------------------------------------------------
-- The embedding dimension is FIXED at 1536 to match `text-embedding-3-small`-
-- class models (the default `AI_EMBED_MODEL`). Changing the model requires a
-- NEW migration that drops and recreates `document_chunks.embedding`, the HNSW
-- index, and a full re-embed of every ready document — do not edit this file
-- to change the dimension. `tests/integration/ai-ingestion.test.ts` asserts
-- `vector_dims(embedding) = 1536`, so a mismatch fails loudly.
--
-- ---------------------------------------------------------------------------
-- Shape of this migration (spec: docs/prs/PR-12-ai-document-foundation.md)
-- ---------------------------------------------------------------------------
--   1. Three tables:
--        * `study_ai_documents` — one row per ingested `study_resources`
--          document (PK = resource_id, ON DELETE CASCADE so resource deletion
--          and moderation removal clean up automatically). Holds the
--          `pending → extracting → chunking → embedding → ready | failed`
--          state machine plus two transient columns (`extracted_text`,
--          `pending_chunks`) that carry work between the client-driven,
--          one-step-per-request ingest calls. They are cleared the moment a
--          document reaches `ready`.
--        * `document_chunks` — ordered chunk text + `vector(1536)` embedding,
--          written only by the ingest RPCs, with a deterministic
--          `chunk_hash = sha256(resource_id || ordinal || text)` so re-runs are
--          idempotent, and `unique (resource_id, ordinal)`.
--        * `ai_usage` — a small per-call ledger (`embed_bytes`,
--          `embed_tokens`, later `chat_tokens`) accumulated during ingest;
--          daily caps are computed with `sum` inside the RPCs.
--   2. Writes to all three tables travel through SECURITY DEFINER RPCs
--      ("RPC-only writes"): `authenticated` gets SELECT grants and read
--      policies only — no INSERT/UPDATE/DELETE on `study_ai_documents` or
--      `document_chunks`, no INSERT on `ai_usage`. The state machine therefore
--      lives server-side and a direct PostgREST write cannot poison another
--      member's chunk table.
--   3. `match_document_chunks` is SECURITY DEFINER with the authorization
--      guard inside (spec allows either style): caller room membership is
--      checked for room scope, personal scope is pinned to
--      `resource.owner_id = auth.uid()`, and only `status = 'ready'`
--      documents are ever returned. A non-member gets zero rows even with a
--      perfectly crafted query embedding.
--   4. Quota: `ai_usage` is accumulated inside `ingest_record_chunk` and the
--      daily byte cap is re-checked there (route pre-checks too, so no
--      provider call is made when over cap; the in-DB check is the race-safe
--      authority for direct RPC callers).
--   5. `vector` extension: installed into the `extensions` schema so every
--      reference in this file (and inside `set search_path = ''` functions)
--      can be schema-qualified. A stack that already has the extension in a
--      different schema is normalised with `alter extension … set schema`;
--      if that cannot move it, the migration fails loudly instead of leaving
--      ambiguous type references behind.
--   6. Explicitly out, same as 0005/0010: no OCR, no new storage operations,
--      no changes to 0001–0012, no widened grants on `study_resources`, no
--      `USING (true)` policy anywhere.
--
-- Identity is always `auth.uid()`. `set search_path = ''` pins the search
-- path and every reference is schema-qualified. Execute on the RPCs is revoked
-- from PUBLIC and anon and granted only to authenticated; the helper
-- `ai_resource_for_ingest` keeps execute revoked from the API roles entirely —
-- only this migration's SECURITY DEFINER functions call it.

-- ---------------------------------------------------------------------------
-- Extension
-- ---------------------------------------------------------------------------

create schema if not exists extensions;

create extension if not exists vector with schema extensions;

-- Normalise a stack that already installed `vector` somewhere else, so the
-- `extensions.vector(1536)` references below always resolve. Fails loudly if
-- the extension cannot be moved rather than silently installing a second copy.
do $$
begin
  if exists (
    select 1
    from pg_catalog.pg_extension e
    join pg_catalog.pg_namespace n on n.oid = e.extnamespace
    where e.extname = 'vector' and n.nspname <> 'extensions'
  ) then
    execute 'alter extension vector set schema extensions';
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- Table: study_ai_documents
-- ---------------------------------------------------------------------------

create table public.study_ai_documents (
  resource_id uuid primary key
    references public.study_resources (id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending', 'extracting', 'chunking', 'embedding', 'ready', 'failed')),
  -- Closed list of everything a failed/resumable row may carry. The values are
  -- validated again in `ingest_mark_failed`; the CHECK is the backstop.
  error_code text
    check (
      error_code is null
      or error_code in (
        'no_text_layer',
        'extract_failed',
        'extracted_too_large',
        'ingest_failed',
        'ai_quota_exceeded',
        'ai_provider_failed'
      )
    ),
  chunk_count int not null default 0 check (chunk_count >= 0),
  extracted_bytes bigint not null default 0 check (extracted_bytes >= 0),
  embedding_tokens bigint not null default 0 check (embedding_tokens >= 0),
  model text,
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  -- Transient step state for the client-driven, one-step-per-request pipeline:
  --   * extracted_text  — normalized text of the last successful extract step
  --                       ("\f" separates PDF pages so page references survive
  --                       the round trip); nulled when the document is ready.
  --   * pending_chunks  — the chunk drafts written by the chunk step, waiting
  --                       for the embed step to attach vectors; nulled when
  --                       the document is ready.
  -- Readable only through RLS by the same audience that can read the chunks
  -- (or download the file itself), never serialised into an API response
  -- except as the transient input to an embedding call the reader could make
  -- themselves. No separate table: one row, one policy, one audience.
  extracted_text text,
  pending_chunks jsonb,
  constraint study_ai_documents_pending_chunks_shape check (
    pending_chunks is null or jsonb_typeof(pending_chunks) = 'array'
  ),
  constraint study_ai_documents_started_after check (
    completed_at is null or started_at is null or completed_at >= started_at
  )
);

-- The `updated_at` trigger is the clock for the sweep (stuck rows older than
-- five minutes). One nuance versus `study_resources`: an explicit rewrite of
-- `updated_at` is honoured (new value differs from old) so tests can
-- simulate the passage of time the same way focus-session tests backdate
-- `started_at`; every other update — which can only come from the SECURITY
-- DEFINER RPCs, since no UPDATE grant exists — is stamped with `now()`.
create or replace function public.study_ai_documents_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.updated_at = old.updated_at then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

create trigger study_ai_documents_set_updated_at
  before update on public.study_ai_documents
  for each row
  execute function public.study_ai_documents_touch();

revoke execute on function public.study_ai_documents_touch()
  from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Table: document_chunks
-- ---------------------------------------------------------------------------

create table public.document_chunks (
  id uuid primary key default gen_random_uuid(),
  resource_id uuid not null
    references public.study_ai_documents (resource_id) on delete cascade,
  ordinal int not null check (ordinal >= 0),
  text text not null check (char_length(text) between 1 and 16000),
  tokens int not null check (tokens between 1 and 100000),
  -- Fixed at 1536 — see the header. The column check is what rejects a vector
  -- of the wrong width even when the insert travels through a SECURITY DEFINER
  -- RPC (the RPC validates first for a clean error; this is the backstop).
  embedding extensions.vector(1536) not null,
  page_start int check (page_start is null or page_start between 1 and 1000000),
  heading text check (heading is null or char_length(heading) <= 500),
  -- sha256(resource_id || ordinal || text), computed inside
  -- `ingest_record_chunk` (never taken from a client payload).
  chunk_hash text not null check (char_length(chunk_hash) = 64),
  unique (resource_id, ordinal)
);

-- HNSW with pgvector's defaults (m = 16, ef_construction = 64). Defaults are
-- deliberate for v1: they need no tuning for document counts of this scale.
-- Build cost is the point to know — HNSW builds lazily per inserted batch and
-- prefers maintenance_work_mem; at a few thousand chunks this is milliseconds,
-- and it is paid inside `ingest_record_chunk`'s transaction.
create index document_chunks_embedding_hnsw_idx
  on public.document_chunks
  using hnsw (embedding extensions.vector_cosine_ops);

-- Sweep support: find stuck non-terminal rows quickly. Partial on
-- `error_code is null` because rows carrying an error are never swept (they
-- wait for an explicit user retry).
create index study_ai_documents_sweep_idx
  on public.study_ai_documents (updated_at)
  where status not in ('ready', 'failed') and error_code is null;

